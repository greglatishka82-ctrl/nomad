async def seed():
    await init_db()
    async with async_session() as db:
        existing = await db.execute(select(FAQItem))
        if existing.scalars().all():
            print("FAQ уже наполнен, пропускаем.")
            return

        for question, answer, sort_order in FAQ_DATA:
            db.add(FAQItem(
                question=question,
                answer=answer,
                sort_order=sort_order,
                is_active=True,
            ))
        await db.commit()
        print(f"Добавлено {len(FAQ_DATA)} вопросов в FAQ.")


if __name__ == "__main__":
    asyncio.run(seed())

async def seed():
    await init_db()
    added = updated = 0
    async with async_session() as db:
        existing = (await db.execute(select(FAQItem))).scalars().all()
        by_order = {}
        for item in existing:
            # при дублях оставляем первый по id
            if item.sort_order not in by_order:
                by_order[item.sort_order] = item

        for question, answer, sort_order in FAQ_DATA:
            item = by_order.get(sort_order)
            if item is None:
                db.add(FAQItem(
                    question=question,
                    answer=answer,
                    sort_order=sort_order,
                    is_active=True,
                ))
                added += 1
            elif item.question != question or item.answer != answer:
                item.question = question
                item.answer = answer
                item.is_active = True
                updated += 1
        await db.commit()
    print(f"FAQ: добавлено {added}, обновлено {updated}.")


if __name__ == "__main__":
    asyncio.run(seed())
